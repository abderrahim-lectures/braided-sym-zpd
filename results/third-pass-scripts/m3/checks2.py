"""Second pass: (A) the two 'not of the form f(xy)' claims, machine-decided;
(B) the *recalled* Bresar Theorem 2.27 as the paper quotes it
    (finite-dim unital: zpd  <=>  generated by idempotents), tested on all
    unital associative algebras of dim <= 3 over F_2 and dim <= 2 over F_3.

Everything is exact over F_p.  An algebra of dimension d is a structure tensor
T[i][j] = tuple of d coordinates of e_i * e_j.  We take e_0 = 1.
"""
import itertools

# ---------- linear algebra over F_p ----------
def solve(A, b, p):
    """Solutions x of A x = b (A list of rows, b list). Returns (consistent, one solution)."""
    m = len(A); n = len(A[0]) if m else 0
    M = [ [A[i][j] % p for j in range(n)] + [b[i] % p] for i in range(m) ]
    piv = []
    r = 0
    for c in range(n):
        pr = None
        for i in range(r, m):
            if M[i][c] % p:
                pr = i; break
        if pr is None: continue
        M[r], M[pr] = M[pr], M[r]
        inv = pow(M[r][c], -1, p)
        M[r] = [v*inv % p for v in M[r]]
        for i in range(m):
            if i != r and M[i][c] % p:
                f = M[i][c]
                M[i] = [(M[i][j] - f*M[r][j]) % p for j in range(n+1)]
        piv.append(c); r += 1
        if r == m: break
    # inconsistent row?
    for i in range(m):
        if all(v % p == 0 for v in M[i][:n]) and M[i][n] % p:
            return False, None
    x = [0]*n
    for i, c in enumerate(piv):
        x[c] = M[i][n]
    return True, x

def rank(rows, p):
    rows = [[v % p for v in r] for r in rows]
    if not rows: return 0
    n = len(rows[0]); r = 0
    for c in range(n):
        pr = None
        for i in range(r, len(rows)):
            if rows[i][c]: pr = i; break
        if pr is None: continue
        rows[r], rows[pr] = rows[pr], rows[r]
        inv = pow(rows[r][c], -1, p)
        rows[r] = [v*inv % p for v in rows[r]]
        for i in range(len(rows)):
            if i != r and rows[i][c]:
                f = rows[i][c]
                rows[i] = [(rows[i][j] - f*rows[r][j]) % p for j in range(n)]
        r += 1
    return r

def span_dim(tensors, p):
    return rank(tensors, p) if tensors else 0

# ---------- generic algebra toolkit ----------
def mul(T, x, y, p):
    d = len(x)
    out = [0]*d
    for i in range(d):
        if not x[i]: continue
        for j in range(d):
            if not y[j]: continue
            c = x[i]*y[j] % p
            row = T[i][j]
            for k in range(d):
                if row[k]:
                    out[k] = (out[k] + c*row[k]) % p
    return tuple(out)

def els(p, d):
    return list(itertools.product(range(p), repeat=d))

def is_zpd(T, p):
    d = len(T)
    # rank of m_bar : A(x)A -> A
    cols = []
    for i in range(d):
        for j in range(d):
            cols.append(list(T[i][j]))
    # mu_bar is d x d^2: rows must be the coordinate rows -> build properly
    rows = [[cols[i*d+j][k] for i in range(d) for j in range(d)] for k in range(d)]
    rk = rank(rows, p)
    dimker = d*d - rk
    tens = []
    for x in els(p, d):
        for y in els(p, d):
            if mul(T, x, y, p) == tuple([0]*d):
                tens.append(tuple(x[i]*y[j] % p for i in range(d) for j in range(d)))
    return span_dim(tens, p) == dimker, dimker

def idempotent_closure(T, p):
    """smallest subalgebra (subspace closed under products) containing all idempotents"""
    d = len(T)
    idem = [x for x in els(p, d) if mul(T, x, x, p) == x]
    # span of idem, then close under multiplication until stable
    basis = []
    def add(v):
        v = [c % p for c in v]
        for b in basis:
            piv = next(i for i, c in enumerate(b) if c)
            if v[piv]:
                f = v[piv]
                v = [(v[i] - f*b[i]) % p for i in range(d)]
        if any(v):
            piv = next(i for i, c in enumerate(v) if c)
            inv = pow(v[piv], -1, p)
            basis.append(tuple(c*inv % p for c in v))
            basis.sort(key=lambda b: next(i for i, c in enumerate(b) if c))
            return True
        return False
    for v in idem: add(list(v))
    changed = True
    while changed:
        changed = False
        cur = []
        for coef in els(p, len(basis)):
            vec = [0]*d
            for ci, b in zip(coef, basis):
                for k in range(d):
                    vec[k] = (vec[k] + ci*b[k]) % p
            cur.append(tuple(vec))
        if not cur: cur = [tuple([0]*d)]
        for u in cur:
            for v in cur:
                if add(list(mul(T, u, v, p))): changed = True
    return len(basis) == d

def unital_algebras(p, d):
    """all structure tensors with e_0 = 1, associative, not checked for isomorphism"""
    if d == 1:
        yield [[(1,)]]
        return
    free = [(i, j) for i in range(1, d) for j in range(1, d)]
    nfree = len(free)*d
    bnd = p**nfree
    for code in range(bnd):
        c = code
        T = [[tuple(1 if k == j else 0 for k in range(d)) if i == 0 else tuple([0]*d) for j in range(d)] for i in range(d)]
        for (i, j) in free:
            vec = []
            for _ in range(d):
                vec.append(c % p); c //= p
            T[i][j] = tuple(vec)
        # unit rows/cols
        for j in range(d):
            T[0][j] = tuple(1 if k == j else 0 for k in range(d))
            T[j][0] = tuple(1 if k == j else 0 for k in range(d))
        # associativity
        ok = True
        for i in range(d):
            for j in range(d):
                for k in range(d):
                    if mul(T, T[i][j], tuple(1 if q == k else 0 for q in range(d)), p) != \
                       mul(T, tuple(1 if q == i else 0 for q in range(d)), T[j][k], p):
                        ok = False; break
                if not ok: break
            if not ok: break
        if ok:
            yield T

def thm227(p, d):
    n = 0; agree = 0; bad = []
    zpds = 0; idemgen = 0
    for T in unital_algebras(p, d):
        n += 1
        z, _ = is_zpd(T, p)
        g = idempotent_closure(T, p)
        zpds += z; idemgen += g
        if z == g: agree += 1
        else: bad.append(T)
    print(f"  F_{p}, dim {d}: {n} unital associative algebras ({zpds} zpd, {idemgen} generated by idempotents), "
          f"agreement {agree}/{n}" + ("" if not bad else f"  MISMATCHES: {len(bad)}"))
    for T in bad[:3]:
        print("    mismatch:", T)

def no_f_form(mu, T, p, d):
    """decide whether mu(x,y) = f(x*y) for some linear f: A -> A"""
    # unknowns: d*d entries of f; equations for every pair of basis elements (d*d*d equations)
    A = []; b = []
    for i in range(d):
        for j in range(d):
            prod = T[i][j]                    # e_i * e_j
            lhs = mu(tuple(1 if q == i else 0 for q in range(d)),
                     tuple(1 if q == j else 0 for q in range(d)))
            # f(prod) = sum_k prod[k] * f(e_k); f(e_k) = unknown (k-th block of d)
            row = [0]*(d*d); 
            for k in range(d):
                for out in range(d):
                    row[k*d + out] = prod[k] if out == 0 else 0
            # do it properly: the out-th coordinate of f(prod)
            for out in range(d):
                row = [0]*(d*d)
                for k in range(d):
                    row[k*d + out] = prod[k] % p
                A.append(row); b.append(lhs[out] % p)
    return solve(A, b, p)

def mat2_mul(x, y, p):
    a,b,c,d = x; e,f,g,h = y
    return ((a*e+b*g) % p, (a*f+b*h) % p, (c*e+d*g) % p, (c*f+d*h) % p)

def conj(x):
    a,b,c,d = x; return (a, (-b) % 3, (-c) % 3, d)

