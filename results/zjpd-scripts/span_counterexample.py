#!/usr/bin/env python3
"""Idempotents of M_n(K[eps]) do not span it, although they generate it.

Exact arithmetic over F_p.  Two independent checks:

  * (n, p) = (2, 3): full enumeration of all 3^8 elements of M_2(F_3[eps]).
  * (n, p) = (2, 5) and (3, 3): the idempotents are enumerated through their Peirce
    description (a = X + eps*Y is idempotent iff X*X = X and X*Y + Y*X = Y), whose
    second ingredient is computed from scratch: for every idempotent X the solution
    space of Y |-> X*Y + Y*X - Y is obtained by elimination.  The full enumeration at
    (2, 3) validates that description; the count of idempotents it predicts there
    (110 = p^3 (p+1) + 2) is the count the enumeration finds.

Prints, for each case, the number of idempotents, the dimension of their span,
whether eps*E11 and eps*1 lie in that span, and the dimension of the subalgebra
generated by the idempotents (computed by closure under multiplication).

Used by results/zjpd-statement-audit.md, section 2.  Run:  python3 span_counterexample.py
"""
import itertools
import sys


def make_mul(n, p):
    def mul(X, Y):
        return tuple(sum(X[n * i + k] * Y[n * k + j] for k in range(n)) % p
                     for i in range(n) for j in range(n))
    return mul


def rank(vectors, ncol, p):
    M = [list(v) for v in vectors]
    r = 0
    for c in range(ncol):
        piv = None
        for i in range(r, len(M)):
            if M[i][c] % p:
                piv = i
                break
        if piv is None:
            continue
        M[r], M[piv] = M[piv], M[r]
        inv = pow(M[r][c], -1, p)
        M[r] = [(x * inv) % p for x in M[r]]
        for i in range(len(M)):
            if i != r and M[i][c] % p:
                f = M[i][c]
                M[i] = [(a - f * b) % p for a, b in zip(M[i], M[r])]
        r += 1
    return r


def kernel_of_operator(rows, nvar, p):
    """Basis of {y : rows * y = 0} for a matrix given as a list of rows."""
    M = [r[:] for r in rows]
    pivots = []
    r = 0
    for c in range(nvar):
        piv = None
        for i in range(r, len(M)):
            if M[i][c] % p:
                piv = i
                break
        if piv is None:
            continue
        M[r], M[piv] = M[piv], M[r]
        inv = pow(M[r][c], -1, p)
        M[r] = [(x * inv) % p for x in M[r]]
        for i in range(len(M)):
            if i != r and M[i][c] % p:
                f = M[i][c]
                M[i] = [(a - f * b) % p for a, b in zip(M[i], M[r])]
        pivots.append(c)
        r += 1
    free = [c for c in range(nvar) if c not in pivots]
    basis = []
    for fc in free:
        v = [0] * nvar
        v[fc] = 1
        for ri, pc in enumerate(pivots):
            v[pc] = (-M[ri][fc]) % p
        basis.append(tuple(v))
    return basis


def idempotents_by_enumeration(n, p):
    mul = make_mul(n, p)
    N = n * n
    elems = [tuple(v) for v in itertools.product(range(p), repeat=N)]
    mats = [X for X in elems if mul(X, X) == X]
    ids = []
    for X in mats:
        for Y in elems:
            if all((mul(X, Y)[t] + mul(Y, X)[t] - Y[t]) % p == 0 for t in range(N)):
                ids.append(tuple(list(X) + list(Y)))
    return ids, len(ids)


def idempotents_by_peirce(n, p):
    mul = make_mul(n, p)
    N = n * n
    mats = [tuple(v) for v in itertools.product(range(p), repeat=N)]
    ids = []
    count = 0
    for X in mats:
        if mul(X, X) != X:
            continue
        rows = []
        for t in range(N):
            row = []
            for s in range(N):
                Y = [0] * N
                Y[s] = 1
                Y = tuple(Y)
                row.append((mul(X, Y)[t] + mul(Y, X)[t] - Y[t]) % p)
            rows.append(row)
        ker = kernel_of_operator(rows, N, p)
        count += p ** len(ker)
        for Y in ker:
            ids.append(tuple(list(X) + list(Y)))
    return ids, count


def generated_dimension(n, p):
    """Dimension of the subalgebra generated by the idempotents e_ii and e_ii + b e_ij."""
    mul = make_mul(n, p)
    N = n * n

    def unit(i, j):
        v = [0] * N
        v[n * i + j] = 1
        return tuple(v)

    def emb(X, Y):
        """The element X + eps*Y of A = M_n(K) + eps*M_n(K)."""
        return tuple(list(X) + list(Y))

    def prod(v, g):
        X1, Y1 = tuple(v[:N]), tuple(v[N:])
        X2, Y2 = tuple(g[:N]), tuple(g[N:])
        return emb(mul(X1, X2),
                   tuple((mul(X1, Y2)[t] + mul(Y1, X2)[t]) % p for t in range(N)))

    zero = [0] * N
    # rem:inner's generators, with b = k + k'*eps running over the K-basis of B = F_p[eps]
    gens = [emb(unit(i, i), zero) for i in range(n)]
    for i in range(n):
        for j in range(n):
            if i == j:
                continue
            for k in range(p):
                for kk in range(p):
                    X = tuple((unit(i, i)[t] + k * unit(i, j)[t]) % p for t in range(N))
                    Y = tuple((kk * unit(i, j)[t]) % p for t in range(N))
                    gens.append(emb(X, Y))
    basis, dim = list(gens), rank(gens, 2 * N, p)
    while True:
        cand = [prod(v, g) for v in basis for g in gens]
        new = basis + cand
        d = rank(new, 2 * N, p)
        if d == dim:
            return d
        basis, dim = new, d


def report(n, p, ids_func, label):
    mul = make_mul(n, p)
    N = n * n
    ids, count = ids_func(n, p)
    # sanity: every listed element really is idempotent, i.e. X*X = X and X*Y + Y*X = Y
    for a in ids:
        X = tuple(a[:N])
        Y = tuple(a[N:])
        sq = mul(X, X)
        assert all((sq[t] - X[t]) % p == 0 for t in range(N)), "X not idempotent"
        cross = tuple((mul(X, Y)[t] + mul(Y, X)[t]) % p for t in range(N))
        assert cross == Y, "X*Y + Y*X != Y"
    d = rank(ids, 2 * N, p)
    eps_E11 = tuple([0] * N + [1] + [0] * (N - 1))
    eps_one = tuple([0] * N + [1 if i == j else 0 for i in range(n) for j in range(n)])
    in_E11 = rank(ids + [eps_E11], 2 * N, p) == d
    in_one = rank(ids + [eps_one], 2 * N, p) == d
    dgen = generated_dimension(n, p)
    print(f"n={n}, p={p} ({label}): {count} idempotents, dim span = {d} of {2 * N}, "
          f"eps*E11 in span = {in_E11}, eps*1 in span = {in_one}, dim generated = {dgen}")
    return d, in_E11, in_one, dgen


def main():
    print("M_2(F_3[eps]): idempotents by full enumeration")
    report(2, 3, idempotents_by_enumeration, "enumeration")
    print("M_2(F_5[eps]): idempotents by their Peirce description")
    report(2, 5, idempotents_by_peirce, "Peirce")
    print("M_3(F_3[eps]): idempotents by their Peirce description")
    report(3, 3, idempotents_by_peirce, "Peirce")
    return 0


if __name__ == "__main__":
    sys.exit(main())
