"""m4 (direction d8): check the paper's UNCITED background assertions by computation.

 (1) rem:inner, l.448: "M_n(B) is generated by the idempotents (e_ii + b e_ij) - e_ii".
     Reading A (literal): is Y = (e_ii + b e_ij) - e_ii = b e_ij an idempotent?
     Reading B (Brešar, Cor. 2.4 proof, p. 19): e_ii + b e_ij is the idempotent and
     b e_ij is a *difference* of two idempotents.
     B = M_2(F_2) (noncommutative, unital), n = 3, so M_3(B) ~ M_6(F_2), dim 36 over F_2.
 (2) ex:dual, l.412: "The only idempotents of A are 0 and 1, so A is not generated by
     idempotents", A = K[e]/(e^2), for K = F_2, F_3, F_5, F_7.
 (3) l.309: in char 2 the map mu = 2xy is zero, so the hypothesis of def:determined
     forces phi = 0 and every algebra is determined by mu.  Checked on M_2(F_2).
Run:  python3 results/audit-scripts/m4-uncited-background.py
"""
import itertools
import numpy as np

def mat(A):  # one of the 16 2x2 matrices over F_2, from 4 bits
    b = [np.array([[1, 0], [0, 0]]), np.array([[0, 1], [0, 0]]),
         np.array([[0, 0], [1, 0]]), np.array([[0, 0], [0, 1]])]
    M = np.zeros((2, 2), dtype=np.int64)
    for k in range(4):
        if (A >> k) & 1:
            M = M + b[k]
    return M % 2

p, n = 2, 3
N = 2 * n
def mm(X, Y): return (X @ Y) % p
def E(i, j):
    M = np.zeros((n, n), dtype=np.int64); M[i, j] = 1; return M
def blk(b, i, j): return np.kron(E(i, j), b) % p

Bmats = [mat(a) for a in range(16)]
Eii = {i: blk(np.eye(2, dtype=np.int64), i, i) for i in range(n)}

# ---- (1) reading A: are the paper's "idempotents" (e_ii + b e_ij) - e_ii idempotent? ----
notidem, total = 0, 0
for i, j in itertools.permutations(range(n), 2):
    for b in Bmats:
        if not b.any():
            continue
        Y = blk(b, i, j); total += 1
        if np.array_equal(mm(Y, Y), Y): notidem += 1
print(f"CHECK 1A  literal reading: for the {total} cases i!=j, b!=0 in M_3(M_2(F_2)), "
      f"b e_ij is idempotent in {notidem} cases.  (b e_ij)^2 = 0 always "
      f"(e_ij e_ij = 0, i != j), so the paper's elements are square-zero, not idempotent.")

# ---- (1b) reading B: e_ii + b e_ij is idempotent ----
bad = [(i, j, int(b.sum())) for i, j in itertools.permutations(range(n), 2) for b in Bmats
       if not np.array_equal(mm((Eii[i] + blk(b, i, j)) % p, (Eii[i] + blk(b, i, j)) % p),
                             (Eii[i] + blk(b, i, j)) % p)]
print("CHECK 1B  e_ii + b e_ij is idempotent for all i != j and all 16 b of M_2(F_2):",
      "YES" if not bad else f"NO {bad[:3]}")

# ---- (1c) the corrected generating set generates M_n(B) ----
basis = []
def add(M):
    w = (M.reshape(-1) % p).copy()
    for bv in basis:
        piv = int(np.argmax(bv != 0))
        if w[piv]:
            w = (w + bv) % p
    if w.any():
        basis.append(w); return True
    return False
for i, j in itertools.permutations(range(n), 2):
    for b in Bmats:
        add((Eii[i] + blk(b, i, j)) % p)
add(Eii[0])
changed = True
while changed:
    changed = False
    cur = [np.array(b, dtype=np.int64).reshape(N, N) for b in list(basis)]
    for X in cur:
        for Y in cur:
            if add(mm(X, Y)):
                changed = True
print(f"CHECK 1C  dim of the algebra generated by {{e_ii + b e_ij : i!=j, b in B}} "
      f"inside M_3(M_2(F_2)): {len(basis)} (full dimension 36 -> generates)")

# ---- (2) dual numbers ----
for q in [2, 3, 5, 7]:
    mul = lambda x, y: ((x[0]*y[0]) % q, (x[0]*y[1] + x[1]*y[0]) % q)
    els = [(a, b) for a in range(q) for b in range(q)]
    idem = [x for x in els if mul(x, x) == x]
    span = set(idem); frontier = set(idem)
    while frontier:
        new = set()
        for x in frontier:
            for y in span:
                z = mul(x, y); s = ((x[0]+y[0]) % q, (x[1]+y[1]) % q)
                for e in (z, s):
                    if e not in span: new.add(e)
        frontier = new; span |= new
    unital = span | {(a, 0) for a in range(q)}
    print(f"CHECK 2   A = F_{q}[e]/(e^2): idempotents {idem}; subalgebra they generate: "
          f"{len(span)}/{q*q} elements (unital: {len(unital)}/{q*q}); "
          f"generates A: {len(unital) == q*q}")

# ---- (3) char 2 ----
A2 = [mat(a) for a in range(16)]
z = sum(1 for x in A2 for y in A2 if not (2 * mm(x, y) % 2).any())
print(f"CHECK 3   over F_2, mu(x,y) = 2xy = 0 for {z}/{16*16} pairs: mu is identically 0, "
      f"so only phi = 0 satisfies def:determined and it factors through mu.")
