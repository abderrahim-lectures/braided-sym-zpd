def main():
    cache = {k: pages(k) for k in SOURCES}
    bad = 0
    for src, anchor, desc in CLAIMS:
        rx = anchor_regex(anchor)
        hits = [(i + 1, sorted(set(pg["nums"]))) for i, pg in enumerate(cache[src])
                if rx.search(pg["norm"])]
        if not hits:
            bad += 1
            print(f"MISS  [{src}] {desc}\n        anchor={anchor!r}")
            continue
        locs = "; ".join(
            f"pdf p.{p} | head={cache[src][p-1]['head']!r} | foot={cache[src][p-1]['foot']!r}"
            for p, n in hits)
        print(f"ok    [{src}] {desc}\n        -> {locs}")
    print(f"\n{len(CLAIMS) - bad}/{len(CLAIMS)} anchors located; {bad} misses.")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
