REFS = ".scratch/refs/braided-sym-zpd-v7-references/"
# File names in the folder are literal copies of the zip entries, so the Brešar
# file is spelled with "#U0161" in place of "š".  Resolve by prefix instead.
_PREFIX = {"adrabi": "1-", "bresar": "2-", "hj": "3-"}
SOURCES = {k: REFS + [f for f in __import__("os").listdir(REFS) if f.startswith(v)][0]
           for k, v in _PREFIX.items()}

_ws = re.compile(r"\s+")


def pages(key):
    txt = subprocess.run(["pdftotext", "-layout", SOURCES[key], "-"],
                         check=True, capture_output=True).stdout.decode("utf-8")
    out = []
    for raw in txt.split("\f"):
        lines = [l for l in raw.split("\n") if l.strip()]
        norm = " " + _ws.sub(" ", raw).strip() + " "
        nums = []
        for l in (lines[:2] + lines[-2:]):
            nums += [int(t) for t in re.findall(r"\b\d{1,3}\b", l)]
        out.append({"norm": norm, "lines": lines, "nums": nums,
                    "head": lines[0].strip() if lines else "",
                    "foot": lines[-1].strip() if lines else ""})
    return out


