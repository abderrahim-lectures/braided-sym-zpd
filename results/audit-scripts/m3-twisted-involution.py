#!/usr/bin/env python3
"""m3 verifier for the twisted braiding (paper ll.129, 134, 193, 323-334).

Claim under test -- Adrabi 2026, Section 4, printed p. 10:
    "We need alpha^2 = id for the following reason.  Applying sigma_alpha below
     twice gives x (x) y -> alpha^2(x) (x) alpha^2(y), so sigma_alpha is an
     involution of A (x) A exactly when alpha is involutive."
i.e. sigma_alpha^2 = id  <=>  alpha^2 = id.

The paper allows alpha to be an arbitrary linear map and still calls
sigma_alpha a "braiding" (l.134), while its only definition of a
braided-symmetric derivation (l.193 = Adrabi Def. 3.1) requires sigma to be an
involution of A (x) A.  Two exact witnesses:

  E1  A = K^3, alpha = a 3-cycle.  A is commutative, unital, generated by the
      idempotents e1,e2,e3, hence zpd (Bresar 2021, Thm 2.27, p. 30; checked
      here as well by the tensor criterion dim span{e_i(x)e_j : e_ie_j = 0}
      = dim ker mu-bar).  So the paper's Corollary cor:twisted applies to it,
      yet sigma_alpha is not an involution of A (x) A.
  E2  A = M_2(F_3), alpha = conjugation by diag(1,-1) (the alpha of the paper's
      Proposition prop:matrix): alpha^2 = id and sigma_alpha^2 = id, checked on
      the full 16-dimensional space A (x) A.

Run from the repository root:
    python3 results/audit-scripts/m3-twisted-involution.py
"""


def mat_mul(X, Y, mod=None):
    n, m, p = len(X), len(Y), len(Y[0])
    Z = [[sum(X[i][k] * Y[k][j] for k in range(m)) for j in range(p)] for i in range(n)]
    return [[v % mod for v in row] for row in Z] if mod else Z


def is_identity(M):
    n = len(M)
    return all(M[i][j] == (1 if i == j else 0) for i in range(n) for j in range(n))


def kron_sigma(n, alpha, mod=None):
    """Matrix of sigma_alpha on A (x) A for A = K^n with basis e_0..e_{n-1},
    A (x) A basis ordered e_i (x) e_j at index i*n+j.

    sigma_alpha(e_i (x) e_j) = alpha(e_j) (x) alpha(e_i)
                             = sum_{k,l} alpha[k][j] alpha[l][i] e_k (x) e_l.
    """
    S = [[0] * (n * n) for _ in range(n * n)]
    for i in range(n):
        for j in range(n):
            for k in range(n):
                for l in range(n):
                    S[k * n + l][i * n + j] += alpha[k][j] * alpha[l][i]
    if mod:
        S = [[v % mod for v in row] for row in S]
    return S


def basis_name(n, idx):
    return f"e{idx // n + 1} (x) e{idx % n + 1}"


def e1():
    print("E1  A = K^3, alpha = the 3-cycle e1 -> e3 -> e2 -> e1")
    n = 3
    alpha = [[0, 1, 0], [0, 0, 1], [1, 0, 0]]      # alpha(e_j) = column j
    S = kron_sigma(n, alpha)
    S2 = mat_mul(S, S)
    print("    alpha^2 == id          :", is_identity(mat_mul(alpha, alpha)))
    print("    sigma_alpha^2 == id    :", is_identity(S2))
    v = [0] * (n * n)
    v[0] = 1                                        # e1 (x) e1
    Sv = [sum(S[i][j] * v[j] for j in range(n * n)) for i in range(n * n)]
    S2v = [sum(S2[i][j] * v[j] for j in range(n * n)) for i in range(n * n)]
    print("    sigma_alpha(e1 (x) e1)   =", [basis_name(n, i) for i, c in enumerate(Sv) if c])
    print("    sigma_alpha^2(e1 (x) e1) =", [basis_name(n, i) for i, c in enumerate(S2v) if c],
          "= alpha^2(e1) (x) alpha^2(e1) != e1 (x) e1")
    # A = K^3 is zpd: zero products among the basis pairs are exactly e_i e_j, i != j,
    # giving 6 tensors; rank(mu-bar) = dim A = 3, so dim ker(mu-bar) = 9 - 3 = 6.
    zero_pairs = [(i, j) for i in range(n) for j in range(n) if i != j]
    print("    zero-product basis pairs:", [(f"e{i+1}", f"e{j+1}") for i, j in zero_pairs])
    print(f"    dim span{{e_i (x) e_j : e_i e_j = 0}} = {len(zero_pairs)}, "
          f"dim ker mu-bar = {n*n} - {n} = {n*n-n}  -> A is zpd (paper Cor. cor:criterion)")
    print("    => Corollary cor:twisted applies, but sigma_alpha is not an involution.")
    print()


def e2():
    print("E2  A = M_2(F_3), alpha = conjugation by diag(1,-1)")
    n, mod = 2, 3
    units = [(i, j) for i in range(n) for j in range(n)]
    idx = {u: t for t, u in enumerate(units)}       # 4-dimensional A
    D = [[1, 0], [0, -1]]
    Dinv = [[1, 0], [0, -1]]
    # alpha(e_ij) = D[i][i] * Dinv[j][j] * e_ij
    alpha = [[0] * 4 for _ in range(4)]
    for (i, j) in units:
        alpha[idx[(i, j)]][idx[(i, j)]] = (D[i][i] * Dinv[j][j]) % mod
    S = kron_sigma(4, alpha, mod=mod)               # 16 x 16 over F_3
    S2 = mat_mul(S, S, mod=mod)
    print("    alpha^2 == id          :", is_identity(mat_mul(alpha, alpha, mod=mod)))
    print("    sigma_alpha^2 == id    :", is_identity(S2))
    print("    (A (x) A has dimension 16, exactly as in the proof of prop:matrix)")
    print()


if __name__ == "__main__":
    e1()
    e2()
