print("\n=== (c) Bresar Cor 2.4 identity, S = M_2(F_3), n = 2,3 ===")


def mm3(X, Y):
    n = len(X)
    return [[sum(X[i][k] * Y[k][j] for k in range(n)) % 3 for j in range(n)] for i in range(n)]


for size in (2, 3):
    ok_idem = True
    ok_diff = True
    for i in range(size):
        for j in range(size):
            if i == j:
                continue
            for s in itertools.product(range(3), repeat=size * size):
                S = [[s[a * size + b] for b in range(size)] for a in range(size)]
                E = [[(1 if (r, c) == (i, i) else 0) + (S[r][c] if (r, c) == (i, j) else 0)
                      for c in range(size)] for r in range(size)]
                E = [[v % 3 for v in row] for row in E]
                Dg = [[1 if (r, c) == (i, i) else 0 for c in range(size)] for r in range(size)]
                if mm3(E, E) != E:
                    ok_idem = False
                # se_ij = E - e_ii
                SE = [[(E[r][c] - Dg[r][c]) % 3 for c in range(size)] for r in range(size)]
                expected = [[S[r][c] % 3 if (r, c) == (i, j) else 0 for c in range(size)]
                            for r in range(size)]
                if SE != expected:
                    ok_diff = False
                if size == 2:
                    if mm3(SE, SE) == SE and any(v for row in SE for v in row):
                        print("   (unexpected: a nonzero se_ij that is idempotent)")
    print(f"  M_{size}(F_3): e_ii + s e_ij idempotent for all s: {ok_idem}; "
          f"(e_ii + s e_ij) - e_ii = s e_ij: {ok_diff}")

print("\n=== (d) the new rem:inner identities, and generation for noncommutative B ===")
# M_n(S) with S = M_2(F_2), n = 2, identified with M_4(F_2) by blocks.
p2, s = 2, 2


def block(i, j, b):
    """the n x n block matrix (n = 2) with b in block (i, j), s x s blocks."""
    M = [[0] * (2 * s) for _ in range(2 * s)]
    for r in range(s):
        for c in range(s):
            M[i * s + r][j * s + c] = b[r][c] % p2
    return M


def mm4(X, Y, p=2, N=4):
    return [[sum(X[i][k] * Y[k][j] for k in range(N)) % p for j in range(N)] for i in range(N)]


def add4(X, Y, p=2):
    return [[(X[i][j] + Y[i][j]) % p for j in range(4)] for i in range(4)]


def flat(M):
    return tuple(v for row in M for v in row)


ALLB = [[[a, b], [c, d]] for a in range(p2) for b in range(p2) for c in range(p2) for d in range(p2)]
idem_ok = diff_ok = diag_ok = True
gens = set()
for i in range(2):
    for j in range(2):
        for b in ALLB:
            if i == j:
                continue
            E = add4(block(i, i, [[1, 0], [0, 1]]), block(i, j, b))
            if mm4(E, E) != E:
                idem_ok = False
            gens.add(flat(E))
            if add4(E, block(i, i, [[1, 0], [0, 1]])) != block(i, j, b):
                diff_ok = False
            if mm4(block(i, j, b), block(j, i, [[1, 0], [0, 1]])) != block(i, i, b):
                diag_ok = False
    gens.add(flat(block(i, i, [[1, 0], [0, 1]])))
print(f"  e_ii + b e_ij idempotent for all b: {idem_ok}; (e_ii+b e_ij) - e_ii = b e_ij: {diff_ok};"
      f" (b e_ij)(e_ji) = b e_ii: {diag_ok}")
print(f"  e_ii + b e_ij idempotent in M_2(M_2(F_2)); number of generators: {len(gens)}")

# closure of the F_2-span of the generators under multiplication
def closure(gens, p=2, N=4):
    els = {g for g in gens}
    elts = list(els)
    changed = True
    while changed:
        changed = False
        cur = list(els)
        for a in cur:
            A = [[a[i * N + j] for j in range(N)] for i in range(N)]
            for b in cur:
                B = [[b[i * N + j] for j in range(N)] for i in range(N)]
                z = flat(mm4(A, B))
                if z not in els:
                    els.add(z)
                    changed = True
    # linear span
    span = {tuple([0] * (N * N))}
    vecs = list(els)
    changed = True
    while changed:
        changed = False
        for v in vecs:
            for w in list(span):
                z = tuple((v[i] + w[i]) % p for i in range(N * N))
                if z not in span:
                    span.add(z)
                    changed = True
    return els, span


els, span = closure(gens)
print(f"  multiplicative closure: {len(els)} elements; F_2-span of it: {len(span)} of {2**16} "
      f"=> generates all of M_4(F_2): {len(span) == 2**16}")

print("\n=== (e) the new q:noncomm claim: inner alpha on T_2(F_3) ===")
p = 3
prodsT = {}
for i in range(3):
    for j in range(3):
        prodsT[(i, j)] = (0, 0, 0)
prodsT[(0, 0)] = (1, 0, 0)
prodsT[(0, 1)] = (0, 1, 0)   # E_11 E_12 = E_12
prodsT[(1, 2)] = (0, 1, 0)   # E_12 E_22 = E_12
prodsT[(2, 2)] = (0, 0, 1)
algT3 = (p, 3, prodsT)


def mulT3(x, y):
    return tuple(sum(x[i] * y[j] * prodsT[(i, j)][k] for i in range(3) for j in range(3)) % p
                 for k in range(3))


# elements (a,b,c) <-> [[a,b],[0,c]];  D = [[1,0],[0,2]], D^{-1} = [[1,0],[0,2]] (2*2=1 mod 3)
def conj(x, y, D=((1, 0), (0, 2)), Di=((1, 0), (0, 2))):
    X = [[x[0], x[1]], [0, x[2]]]
    Y = [[y[0], y[1]], [0, y[2]]]
    def m2(A, B):
        return [[(A[0][0] * B[0][0] + A[0][1] * B[1][0]) % p,
                 (A[0][0] * B[0][1] + A[0][1] * B[1][1]) % p],
                [(A[1][0] * B[0][0] + A[1][1] * B[1][0]) % p,
                 (A[1][0] * B[0][1] + A[1][1] * B[1][1]) % p]]
    t = m2(m2(D, m2(Y, X)), Di)
    s = m2(X, Y)
    return ((s[0][0] + t[0][0]) % p, (s[0][1] + t[0][1]) % p, (s[1][1] + t[1][1]) % p)


def jorT3(x, y):
    a, b = mulT3(x, y), mulT3(y, x)
    return tuple((a[k] + b[k]) % p for k in range(3))


