n = 2
# basis e0 = E_11, e1 = E_12;  E_11*E_11 = E_11, E_11*E_12 = E_12, E_12 * anything = 0
prods = {}
for i in range(n):
    for j in range(n):
        out = [0] * n
        if (i, j) == (0, 0):
            out[0] = 1
        elif (i, j) == (0, 1):
            out[1] = 1
        prods[(i, j)] = tuple(out)
