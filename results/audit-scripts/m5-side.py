def mul(x, y):
    return tuple(sum(x[i] * y[j] * prods[(i, j)][k] for i in range(n) for j in range(n)) % p
                 for k in range(n))


def jordan(x, y):
    a, b = mul(x, y), mul(y, x)
    return tuple((a[k] + b[k]) % p for k in range(n))


def prod(x, y):
    return mul(x, y)


