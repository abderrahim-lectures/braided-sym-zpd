#!/usr/bin/env python3
"""m2: support check for the internal-consistency finding on Remark 5.5 (rem:inner).

Remark 5.5 says "M_n(B) is generated by the idempotents (e_ii + b e_ij) - e_ii for
i != j with b in B".  Two things are checked in M_2(F_p), exactly:

  (1) is (e_ii + b e_ij) - e_ii = b e_ij idempotent?          -> it is nilpotent
  (2) is e_ii + b e_ij idempotent?                            -> only if 2b = 0
  (3) do the elements b e_ij (i != j) generate the whole algebra?  -> yes for n = 2
so the word "idempotents" is what fails, not the generation.
"""
def mat(rows):
    return tuple(tuple(r) for r in rows)


def mul(X, Y, p):
    n, m, k = len(X), len(Y[0]), len(Y)
    return tuple(tuple(sum(X[i][t] * Y[t][j] for t in range(k)) % p for j in range(m))
                 for i in range(n))


def eq(X, Y):
    return X == Y


for p in (2, 3, 5):
    Z = ((0, 0), (0, 0))
    e11 = ((1, 0), (0, 0))
    e12 = ((0, 1), (0, 0))
    e21 = ((0, 0), (1, 0))
    e22 = ((0, 0), (0, 1))
    u = ((1, 1), (0, 0))          # e11 + 1*e12
    diff = tuple(tuple((u[i][j] - e11[i][j]) % p for j in range(2)) for i in range(2))
    print("p = %d" % p)
    print("   (e11 + e12) - e11 = %s ; is it idempotent? %s ; its square = %s"
          % (diff, eq(mul(diff, diff, p), diff), mul(diff, diff, p)))
    print("   e11 + e12 = u ; u^2 = %s ; idempotent? %s" % (mul(u, u, p), eq(mul(u, u, p), u)))
    print("   e11 + b e12 idempotent for all b in F_p? %s"
          % all(eq(mul(((1, b % p), (0, 0)), ((1, b % p), (0, 0)), p), ((1, b % p), (0, 0)))
                for b in range(p)))
    # generation by the nilpotents e12, e21
    print("   e12 e21 = %s, e21 e12 = %s -> {b e_ij} generates M_2(F_p)? %s"
          % (mul(e12, e21, p), mul(e21, e12, p),
             eq(mul(e12, e21, p), e11) and eq(mul(e21, e12, p), e22)))

