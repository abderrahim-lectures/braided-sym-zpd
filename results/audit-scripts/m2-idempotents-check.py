# Second part: the sentence as it stands after the mid-audit edit,
#   "M_n(B) is generated by the idempotents e_ii and e_ii + b e_ij (i != j, b in B)
#    (indeed be_ij = (e_ii + be_ij) - e_ii and be_ii = (be_ij)e_ji)",
# is checked for a NON-commutative B, namely B = M_2(F_3), n = 2.
# Elements of M_n(B) are n x n arrays of elements of B.
def bmul(X, Y, p):
    return mul(X, Y, p)


def badd(X, Y, p):
    return tuple(tuple((X[i][j] + Y[i][j]) % p for j in range(len(X[0]))) for i in range(len(X)))


def zeroB(p):
    return ((0, 0), (0, 0))


def matB(n, p):
    return [[zeroB(p) for _ in range(n)] for _ in range(n)]


def mmul(X, Y, n, p):
    Z = matB(n, p)
    for i in range(n):
        for j in range(n):
            acc = zeroB(p)
            for t in range(n):
                acc = badd(acc, bmul(X[i][t], Y[t][j], p), p)
            Z[i][j] = acc
    return tuple(tuple(r) for r in Z)


def unit(n, i, p):
    M = matB(n, p)
    M[i][i] = ((1, 0), (0, 1))          # 1_B
    return M


def be(n, i, j, b, p):
    M = matB(n, p)
    M[i][j] = b
    return tuple(tuple(r) for r in M)


def meq(X, Y):
    return X == Y


n, p = 2, 3
for b in (((0, 1), (0, 0)), ((1, 2), (1, 1)), ((0, 0), (1, 0))):
    u = mmul  # alias
    E = unit(n, 0, p)
    d = be(n, 0, 1, b, p)
    left = matB(n, p)
    for i in range(n):
        for j in range(n):
            left[i][j] = badd(E[i][j], d[i][j], p)
    left = tuple(tuple(r) for r in left)
    sq = mmul(left, left, n, p)
    print("B = M_2(F_3), b = %s: (e11 + b e12)^2 == e11 + b e12 ? %s" % (b, meq(sq, left)))
    # be_11 = (be_12)(e_21)
    prod = mmul(d, be(n, 1, 0, ((1, 0), (0, 1)), p), n, p)
    print("   (b e12)(e21) == b e11 ? %s" % meq(prod, be(n, 0, 0, b, p)))
    # and the element the old text displayed: (e11 + b e12) - e11 = b e12
    print("   (b e12)^2 == 0 ? %s" % meq(mmul(d, d, n, p), tuple(tuple(zeroB(p) for _ in range(n)) for _ in range(n))))
